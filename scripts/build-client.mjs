import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const buildDir = path.join(root, "build");
await mkdir(buildDir, { recursive: true });

// 1. Bundle the Milkdown theme (and its nested @imports) into one stylesheet.
await build({
  entryPoints: [path.join(root, "src/client/milkdown-theme.css")],
  bundle: true,
  outfile: path.join(buildDir, "milkdown.css"),
  target: ["chrome120"],
  logLevel: "info",
});

const milkdownCss = await readFile(path.join(buildDir, "milkdown.css"), "utf8");
await writeFile(
  path.join(root, "src/client/generated-milkdown-css.js"),
  `// Generated by scripts/build-client.mjs. Do not edit.\nexport const MILKDOWN_CSS = ${JSON.stringify(milkdownCss)};\n`,
);

// 2. Bundle the browser plugin. React stays external so the shell's module
//    table supplies the single React instance; everything else is inlined.
await build({
  entryPoints: [path.join(root, "src/client/index.js")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: ["chrome120"],
  external: ["react"],
  outfile: path.join(buildDir, "client.body.cjs"),
  minify: true,
  legalComments: "inline",
  define: { "process.env.NODE_ENV": '"production"' },
  loader: { ".css": "text" },
  logLevel: "info",
});

const body = await readFile(path.join(buildDir, "client.body.cjs"), "utf8");
const wrapped = `/**
 * 文档中心 —— 浏览器半身（构建产物）。
 *
 * 由 scripts/build-client.mjs 从 src/client 生成。源码依赖 shell 的 react，
 * 经 esbuild 打包后以 ModuleLoader factory 形式注册。
 *
 * 所有对 DSH 内部加载器（window.__ModuleLoader__）的依赖集中在这个入口，
 * DSH 客户端内核变化时只需要改这一段。
 */
(function registerDocumentCenterClient() {
  const loader = globalThis.__ModuleLoader__;
  if (!loader || typeof loader.load !== "function") {
    throw new Error(
      "dsh-document-center: the DSH client module loader is unavailable. " +
      "This plugin requires DSH 0.2.x Web/Desktop; see docs/UPGRADING.md.",
    );
  }
  loader.load({
    id: "dsh-document-center",
    factory: (require) => {
      const module = { exports: {} };
      const exports = module.exports;
      (function (module, exports, require) {
${body}
      })(module, exports, require);
      return module.exports;
    },
  });
})();
`;
await writeFile(path.join(root, "client.js"), wrapped);
console.log(`client.js ${(Buffer.byteLength(wrapped) / 1024 / 1024).toFixed(2)} MiB`);
